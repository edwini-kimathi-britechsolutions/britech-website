/**
 * Builds the static assets for the PHP edition (php-site/):
 *   - app/data.php + app/icons.php   from src/lib/data.ts and lucide-react (via export.tsx)
 *   - assets/app.css                 Tailwind, compiled from the PHP templates
 *   - assets/editor.js               TipTap blog editor bundle
 * Usage: npm run php:build      (the server never needs Node.js — upload php-site/ as is)
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";
import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const site = path.join(root, "php-site");

/* 1. data + icons → PHP arrays */
const tmp = mkdtempSync(path.join(tmpdir(), "britech-php-"));
execFileSync("npx", ["tsx", path.join(here, "export.tsx"), tmp], { cwd: root, stdio: "inherit" });
const toPhp = (jsonFile, phpFile, comment) => {
  execFileSync("php", [
    "-r",
    `$d = json_decode(file_get_contents($argv[1]), true, 512, JSON_THROW_ON_ERROR);
     file_put_contents($argv[2], "<?php\\n// ${comment}\\n// Generated by scripts/php-build/build.mjs — edit the source, not this file.\\ndefined('BRITECH') || exit;\\n\\nreturn " . var_export($d, true) . ";\\n");`,
    jsonFile,
    phpFile,
  ]);
};
toPhp(path.join(tmp, "data.json"), path.join(site, "app/data.php"), "Site content from src/lib/data.ts (services, industries, stats …).");
toPhp(path.join(tmp, "icons.json"), path.join(site, "app/icons.php"), "Lucide icon shapes (lucide-react), keyed by name.");

/* 2. editor bundle */
await build({
  entryPoints: [path.join(here, "editor.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2019"],
  outfile: path.join(site, "assets/editor.js"),
  legalComments: "none",
  logLevel: "warning",
});

/* 3. Tailwind CSS */
const cssIn = path.join(here, "app.css");
const result = await postcss([tailwind({ optimize: { minify: true } })]).process(readFileSync(cssIn, "utf8"), { from: cssIn });
writeFileSync(path.join(site, "assets/app.css"), result.css);

console.log("PHP edition assets built → php-site/");
